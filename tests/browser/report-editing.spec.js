const { test, expect } = require('@playwright/test');

test('Complete an existing report by following a missing field, then export the saved revision', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/reports/new');
  await page.locator('#title').fill('Edit workflow acceptance sample');
  await page.locator('#severity').selectOption('high');
  await page.locator('#steps').fill('1. Open the app\n2. Open settings');
  await page.getByRole('button', { name: 'Create report', exact: true }).click();
  const detail = new URL(page.url()).pathname;
  await expect(page.locator('#completeness-score')).toHaveText('43%');
  const edit = page.getByRole('link', { name: 'Edit report', exact: true });
  await expect(edit).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: 'Add environment', exact: true }).click();
  await expect(page.locator('#environment')).toBeFocused();
  await expect(page.locator('#title')).toHaveValue('Edit workflow acceptance sample');
  await expect(page.locator('#steps')).toHaveValue('1. Open the app\n2. Open settings');
  await page.locator('#environment').fill('Windows 11 / Chrome');
  await expect(page.locator('#completeness-score')).toHaveText('57%');
  const discard = page.waitForEvent('dialog');
  const cancel = page.getByRole('link', { name: 'Cancel', exact: true }).click();
  const dialog = await discard;
  expect(dialog.type()).toBe('beforeunload');
  await dialog.dismiss();
  await cancel;
  await expect(page.locator('#environment')).toHaveValue('Windows 11 / Chrome');
  await page.locator('#title').fill(' ');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.locator('#form-errors')).toBeFocused();
  await expect(page.locator('#environment')).toHaveValue('Windows 11 / Chrome');
  await page.locator('#title').fill('Edited workflow acceptance sample');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByText('Changes saved. Completeness updated.')).toBeVisible();
  expect(new URL(page.url()).pathname).toBe(detail);
  await expect(page.locator('#completeness-score')).toHaveText('57%');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Edited workflow acceptance sample', exact: true })).toBeVisible();
  const exported = await page.request.get(detail + '/export');
  expect(await exported.text()).toContain('Windows 11 / Chrome');
  await page.getByRole('link', { name: 'Back to reports', exact: false }).click();
  await expect(page.getByRole('link', { name: 'Edited workflow acceptance sample', exact: true })).toHaveCount(1);
  await expect(page.getByRole('link', { name: 'Edit workflow acceptance sample', exact: true })).toHaveCount(0);
});
